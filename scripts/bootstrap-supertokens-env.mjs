/**
 * Local helper: derive SuperTokens Docker + backend env from existing DATABASE_URL.
 * - Does not print secrets
 * - Writes/updates `.env.docker` (gitignored)
 * - Ensures SUPERTOKENS_* keys exist in `.env` (gitignored)
 *
 * Usage: node scripts/bootstrap-supertokens-env.mjs
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const dockerEnvPath = path.join(root, ".env.docker");
const ST_DB = "umind_supertokens";

const parseEnvFile = (filePath) => {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    if (!line || line.trim().startsWith("#")) continue;
    const i = line.indexOf("=");
    if (i < 0) continue;
    const key = line.slice(0, i).trim();
    let val = line.slice(i + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
};

const upsertEnvKeys = (filePath, updates, headerLines = []) => {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
  const lines = existing ? existing.split(/\r?\n/) : [];
  const keys = new Set(Object.keys(updates));
  const next = [];
  const seen = new Set();

  for (const line of lines) {
    const m = line.match(/^([^#=]+)=(.*)$/);
    if (m && keys.has(m[1].trim())) {
      const k = m[1].trim();
      next.push(`${k}=${updates[k]}`);
      seen.add(k);
    } else {
      next.push(line);
    }
  }

  const missing = [...keys].filter((k) => !seen.has(k));
  if (missing.length > 0) {
    if (next.length > 0 && next[next.length - 1] !== "") next.push("");
    for (const h of headerLines) next.push(h);
    for (const k of missing) next.push(`${k}=${updates[k]}`);
  }

  fs.writeFileSync(filePath, next.join("\n").replace(/\n*$/, "\n"), "utf8");
};

const env = parseEnvFile(envPath);
if (!env.DATABASE_URL) {
  console.error("DATABASE_URL missing in .env — cannot derive Postgres credentials.");
  process.exit(1);
}

let dbUrl;
try {
  dbUrl = new URL(env.DATABASE_URL);
} catch {
  console.error("DATABASE_URL is not a valid URL.");
  process.exit(1);
}

if (!/^postgres(ql)?:$/i.test(dbUrl.protocol)) {
  console.error("DATABASE_URL must be a postgresql:// URL.");
  process.exit(1);
}

const user = decodeURIComponent(dbUrl.username || "postgres");
const password = decodeURIComponent(dbUrl.password || "");
const port = dbUrl.port || "5432";
const appDb = (dbUrl.pathname || "").replace(/^\//, "").split("?")[0];

if (!password) {
  console.error("DATABASE_URL has no password; set SUPERTOKENS_POSTGRES_* in .env.docker manually.");
  process.exit(1);
}

if (appDb && appDb === ST_DB) {
  console.error(`DATABASE_URL points at ${ST_DB}; app DB and SuperTokens DB must differ.`);
  process.exit(1);
}

const apiKey =
  env.SUPERTOKENS_API_KEY && env.SUPERTOKENS_API_KEY.length >= 20
    ? env.SUPERTOKENS_API_KEY
    : crypto.randomBytes(32).toString("hex");

const dockerEnv = {
  SUPERTOKENS_API_KEY: apiKey,
  SUPERTOKENS_POSTGRES_HOST: "host.docker.internal",
  SUPERTOKENS_POSTGRES_PORT: port,
  SUPERTOKENS_POSTGRES_USER: user,
  SUPERTOKENS_POSTGRES_PASSWORD: password,
  SUPERTOKENS_POSTGRES_DB: ST_DB,
};

const dockerBody = [
  "# Generated by scripts/bootstrap-supertokens-env.mjs — do not commit.",
  "# Host Postgres credentials derived from backend DATABASE_URL; ST uses a separate database.",
  `SUPERTOKENS_API_KEY=${dockerEnv.SUPERTOKENS_API_KEY}`,
  `SUPERTOKENS_POSTGRES_HOST=${dockerEnv.SUPERTOKENS_POSTGRES_HOST}`,
  `SUPERTOKENS_POSTGRES_PORT=${dockerEnv.SUPERTOKENS_POSTGRES_PORT}`,
  `SUPERTOKENS_POSTGRES_USER=${dockerEnv.SUPERTOKENS_POSTGRES_USER}`,
  `SUPERTOKENS_POSTGRES_PASSWORD=${dockerEnv.SUPERTOKENS_POSTGRES_PASSWORD}`,
  `SUPERTOKENS_POSTGRES_DB=${dockerEnv.SUPERTOKENS_POSTGRES_DB}`,
  "",
].join("\n");

fs.writeFileSync(dockerEnvPath, dockerBody, "utf8");

upsertEnvKeys(
  envPath,
  {
    SUPERTOKENS_CONNECTION_URI: "http://localhost:3567",
    SUPERTOKENS_API_KEY: apiKey,
    SUPERTOKENS_APP_NAME: env.SUPERTOKENS_APP_NAME || "U Mind Staff",
    SUPERTOKENS_API_DOMAIN: env.SUPERTOKENS_API_DOMAIN || "http://localhost:4000",
    SUPERTOKENS_WEBSITE_DOMAIN: env.SUPERTOKENS_WEBSITE_DOMAIN || "http://localhost:3000",
    SUPERTOKENS_API_BASE_PATH: env.SUPERTOKENS_API_BASE_PATH || "/api/v1/staff/auth",
    SUPERTOKENS_WEBSITE_BASE_PATH: env.SUPERTOKENS_WEBSITE_BASE_PATH || "/auth",
  },
  ["# Staff SuperTokens Core (local docker compose → 127.0.0.1:3567)"]
);

console.log("Wrote .env.docker and ensured SUPERTOKENS_* in .env (secrets not printed).");
console.log(`SuperTokens database name: ${ST_DB}`);
console.log("Next: start Docker Desktop, then: docker compose --env-file .env.docker up -d");
